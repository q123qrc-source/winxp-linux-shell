"""Generates Meadow's default wallpaper, "Meadow Hills", as SVG.

Original procedural art (CC-BY-SA-4.0 like the other Meadow artwork): a deep
blue sky that lightens towards the horizon, soft clouds made of overlapping
radial-gradient puffs, and three rolling hills, the nearest one a saturated
green lit from the top left. Only SVG Tiny features are used (gradients and
paths, no filters) so Qt's SVG renderer draws it exactly.

The output is committed (theme/assets/meadow-hills.svg); the
`wallpaper_sync` test regenerates it and fails on any difference.

    gen-wallpaper.py [--output FILE] [--check FILE]
"""
import argparse
import math
import sys

W, H = 1600, 1200

# Sky: top to horizon.
SKY = [(0.0, "#1C5FC9"), (0.45, "#4A8EE6"), (0.78, "#8FC1F5"), (1.0, "#C9E3FB")]

# Clouds: (center x, center y, scale). Each is a cluster of puffs.
CLOUDS = [(330, 230, 1.15), (1080, 150, 0.85), (1380, 330, 0.7), (700, 360, 0.55)]
PUFFS = [(-120, 18, 95, 52), (-40, -12, 120, 70), (70, -4, 130, 66), (160, 20, 90, 46), (20, 30, 170, 44)]

# Hills, back to front: (baseline points as fractions, gradient top, bottom).
HILLS = [
    ([(0.0, 0.70), (0.22, 0.60), (0.48, 0.66), (0.74, 0.57), (1.0, 0.64)], "#7FB75A", "#4F8F35"),
    ([(0.0, 0.80), (0.30, 0.68), (0.62, 0.77), (0.86, 0.70), (1.0, 0.73)], "#6CB33F", "#3E8526"),
    ([(0.0, 0.84), (0.18, 0.76), (0.52, 0.72), (0.80, 0.81), (1.0, 0.79)], "#8ED04B", "#3F9A1E"),
]


def fmt(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def smooth_path(points):
    """A closed path: a smooth curve through `points` (Catmull-Rom as cubic
    Béziers), then down to the bottom corners."""
    pts = [(x * W, y * H) for x, y in points]
    d = [f"M0 {fmt(H)} L{fmt(pts[0][0])} {fmt(pts[0][1])}"]
    for i in range(len(pts) - 1):
        p0 = pts[i - 1] if i > 0 else pts[i]
        p1, p2 = pts[i], pts[i + 1]
        p3 = pts[i + 2] if i + 2 < len(pts) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d.append(f"C{fmt(c1[0])} {fmt(c1[1])} {fmt(c2[0])} {fmt(c2[1])} {fmt(p2[0])} {fmt(p2[1])}")
    d.append(f"L{fmt(W)} {fmt(H)} Z")
    return " ".join(d)


def render():
    out = []
    a = out.append
    a('<?xml version="1.0" encoding="UTF-8"?>')
    a("<!-- SPDX-License-Identifier: CC-BY-SA-4.0")
    a('     "Meadow Hills", original procedural art for Meadow.')
    a("     Generated by tools/gen-wallpaper.py; do not edit by hand. -->")
    a(f'<svg xmlns="http://www.w3.org/2000/svg" version="1.2" baseProfile="tiny" '
      f'width="{W}" height="{H}" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMid slice">')
    a("  <defs>")
    a('    <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">')
    for off, col in SKY:
        a(f'      <stop offset="{off}" stop-color="{col}"/>')
    a("    </linearGradient>")
    a('    <radialGradient id="puff" cx="0.5" cy="0.5" r="0.5">')
    a('      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.95"/>')
    a('      <stop offset="0.55" stop-color="#FFFFFF" stop-opacity="0.75"/>')
    a('      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>')
    a("    </radialGradient>")
    for i, (_, top, bottom) in enumerate(HILLS):
        a(f'    <linearGradient id="hill{i}" x1="0" y1="0" x2="0.25" y2="1">')
        a(f'      <stop offset="0" stop-color="{top}"/>')
        a(f'      <stop offset="1" stop-color="{bottom}"/>')
        a("    </linearGradient>")
    # A soft sunlit sheen on the nearest hill, from the top left.
    a('    <radialGradient id="sheen" cx="0.28" cy="0.0" r="0.55">')
    a('      <stop offset="0" stop-color="#E9FFB0" stop-opacity="0.55"/>')
    a('      <stop offset="1" stop-color="#E9FFB0" stop-opacity="0"/>')
    a("    </radialGradient>")
    a("  </defs>")
    a(f'  <rect width="{W}" height="{H}" fill="url(#sky)"/>')
    for cx, cy, s in CLOUDS:
        a(f'  <g transform="translate({cx} {cy}) scale({s})">')
        for dx, dy, rx, ry in PUFFS:
            a(f'    <ellipse cx="{dx}" cy="{dy}" rx="{rx}" ry="{ry}" fill="url(#puff)"/>')
        a("  </g>")
    for i, (points, _, _) in enumerate(HILLS):
        a(f'  <path d="{smooth_path(points)}" fill="url(#hill{i})"/>')
    a(f'  <path d="{smooth_path(HILLS[-1][0])}" fill="url(#sheen)"/>')
    a("</svg>")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output", help="write the SVG here (default: stdout)")
    ap.add_argument("--check", help="exit 1 if FILE differs from the generated SVG")
    args = ap.parse_args()
    svg = render()
    if args.check:
        with open(args.check, encoding="utf-8") as f:
            if f.read() != svg:
                print(f"{args.check} is out of date; run tools/gen-wallpaper.py --output {args.check}")
                return 1
        return 0
    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(svg)
    else:
        sys.stdout.write(svg)
    return 0


if __name__ == "__main__":
    sys.exit(main())
