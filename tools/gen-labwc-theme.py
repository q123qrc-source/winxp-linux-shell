"""Generate Meadow's labwc window decorations and rc.xml from theme.json.

theme.json is the single source of truth; the files this writes are
committed so packaging needs no generator, and `--check` (a ctest) fails when
they are out of date.

  gen-labwc-theme.py              write decorations/labwc/* and session/labwc/rc.xml
  gen-labwc-theme.py --check      compare instead of writing; exit 1 if stale
  gen-labwc-theme.py --contact-sheet OUT.svg [--scheme luna-blue]
                                  every button state side by side (screenshot test)

Per scheme it writes decorations/labwc/<ThemeName>/labwc/:
  themerc                  labwc theme (see labwc-theme(5), 0.9)
  {iconify,max,max_toggled,close}[_hover]-{active,inactive}.svg

labwc facts this relies on: colors are #rrggbbaa (alpha last, unlike our
#AARRGGBB tokens); title height = max(font, button height) + 2 * padding;
there is no pressed-state button image; borders have a single color; font
sizes are Pango points.
"""
import argparse
import difflib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME_NAMES = {"luna-blue": "Meadow-Luna", "luna-olive": "Meadow-Luna-Olive", "luna-silver": "Meadow-Luna-Silver"}
DEFAULT_SCHEME = "luna-blue"
HEADER = "Generated by tools/gen-labwc-theme.py from theme/{scheme}/theme.json. Do not edit; edit the tokens."


# --- Colors -----------------------------------------------------------------

def parse_color(c):
    """#RRGGBB or #AARRGGBB -> (r, g, b, a) with 0..255 ints."""
    h = c.lstrip("#")
    if len(h) == 6:
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255
    if len(h) == 8:
        return int(h[2:4], 16), int(h[4:6], 16), int(h[6:8], 16), int(h[0:2], 16)
    raise ValueError(f"bad color {c!r}")


def labwc_color(c):
    r, g, b, a = parse_color(c) if isinstance(c, str) else c
    return f"#{r:02x}{g:02x}{b:02x}" + ("" if a == 255 else f"{a:02x}")


def svg_color(c):
    r, g, b, a = parse_color(c)
    return f"#{r:02x}{g:02x}{b:02x}", round(a / 255, 3)


def sample(stops, pos):
    """Color of a token gradient at pos (linear interpolation, like Qt)."""
    stops = sorted(stops, key=lambda s: s["pos"])
    if pos <= stops[0]["pos"]:
        return parse_color(stops[0]["color"])
    for a, b in zip(stops, stops[1:]):
        if a["pos"] <= pos <= b["pos"]:
            t = 0 if b["pos"] == a["pos"] else (pos - a["pos"]) / (b["pos"] - a["pos"])
            ca, cb = parse_color(a["color"]), parse_color(b["color"])
            return tuple(round(x + (y - x) * t) for x, y in zip(ca, cb))
    return parse_color(stops[-1]["color"])


def px_to_pt(px):
    """Pango point size for a pixel size at 96 dpi."""
    return max(1, round(px * 72 / 96))


# --- themerc ----------------------------------------------------------------

def metrics(t):
    w = t["window"]
    size = w["buttons"]["size"]
    pad = (w["titlebar"]["height"] - size) // 2
    return {"button_w": size, "button_h": w["titlebar"]["height"] - 2 * pad, "pad": pad}


def title_texture(prefix, stops):
    # SplitVertical: top half color.splitTo -> color, bottom half colorTo -> colorTo.splitTo.
    return [
        f"{prefix}.title.bg: Gradient SplitVertical",
        f"{prefix}.title.bg.color.splitTo: {labwc_color(sample(stops, 0.0))}",
        f"{prefix}.title.bg.color: {labwc_color(sample(stops, 0.5))}",
        f"{prefix}.title.bg.colorTo: {labwc_color(sample(stops, 0.5))}",
        f"{prefix}.title.bg.colorTo.splitTo: {labwc_color(sample(stops, 1.0))}",
    ]


def themerc(scheme, t):
    w, m = t["window"], metrics(t)
    menu, colors, sw = t["controls"]["menu"], t["colors"], t["windowSwitcher"]
    lines = [
        f"# {HEADER.format(scheme=scheme)}",
        f"# {t['meta']['name']} window decorations for labwc.",
        "",
        "# Frame",
        f"border.width: {w['border']['width']}",
        f"window.active.border.color: {labwc_color(w['border']['activeColor'])}",
        f"window.inactive.border.color: {labwc_color(w['border']['inactiveColor'])}",
        f"window.active.indicator.toggled-keybind.color: {labwc_color(w['border']['activeColor'])}",
        "window.active.shadow.size: 0",
        "window.inactive.shadow.size: 0",
        "",
        "# Title bar: height = button height + 2 * padding",
        f"window.titlebar.padding.width: {w['buttons']['marginRight']}",
        f"window.titlebar.padding.height: {m['pad']}",
        *title_texture("window.active", w["titlebar"]["gradient"]["active"]),
        *title_texture("window.inactive", w["titlebar"]["gradient"]["inactive"]),
        f"window.active.label.text.color: {labwc_color(w['titlebar']['textColor'])}",
        f"window.inactive.label.text.color: {labwc_color(w['titlebar']['inactiveTextColor'])}",
        "window.label.text.justify: left",
        "",
        "# Buttons (SVG files next to this themerc; labwc has no pressed state)",
        f"window.button.width: {m['button_w']}",
        f"window.button.height: {m['button_h']}",
        f"window.button.spacing: {w['buttons']['spacing']}",
        "window.button.hover.bg.color: #00000000",
        f"window.active.button.unpressed.image.color: {labwc_color(w['buttons']['glyphColor'])}",
        f"window.inactive.button.unpressed.image.color: {labwc_color(w['buttons']['glyphColor'])}",
        "",
        "# Menus (window menu, Alt+Space)",
        "menu.border.width: 1",
        f"menu.border.color: {labwc_color(menu['borderColor'])}",
        f"menu.width.min: {menu['widthMin']}",
        f"menu.width.max: {menu['widthMax']}",
        f"menu.items.padding.x: {menu['paddingX']}",
        f"menu.items.padding.y: {menu['paddingY']}",
        f"menu.items.bg.color: {labwc_color(menu['background'])}",
        f"menu.items.text.color: {labwc_color(colors['windowText'])}",
        f"menu.items.active.bg.color: {labwc_color(menu['hoverBackground'])}",
        f"menu.items.active.text.color: {labwc_color(menu['hoverText'])}",
        "menu.separator.width: 1",
        f"menu.separator.padding.width: {menu['separatorPadding']}",
        f"menu.separator.padding.height: {menu['separatorPadding']}",
        f"menu.separator.color: {labwc_color(menu['separatorColor'])}",
        f"menu.title.bg.color: {labwc_color(sample(w['titlebar']['gradient']['active'], 0.5))}",
        f"menu.title.text.color: {labwc_color(w['titlebar']['textColor'])}",
        "menu.title.text.justify: left",
        "",
        "# Window switcher (Alt+Tab) until the shell's own switcher (phase 8)",
        f"osd.bg.color: {labwc_color(colors['windowBackground'])}",
        f"osd.border.color: {labwc_color(menu['borderColor'])}",
        f"osd.border.width: {sw['borderWidth']}",
        f"osd.label.text.color: {labwc_color(colors['windowText'])}",
        f"osd.window-switcher.style-classic.width: {sw['width']}",
        f"osd.window-switcher.style-classic.padding: {sw['padding']}",
        f"osd.window-switcher.style-classic.item.padding.x: {sw['itemPaddingX']}",
        f"osd.window-switcher.style-classic.item.padding.y: {sw['itemPaddingY']}",
        f"osd.window-switcher.style-classic.item.active.border.width: {sw['borderWidth']}",
        f"osd.window-switcher.style-classic.item.active.border.color: {labwc_color(colors['selection'])}",
        f"osd.window-switcher.style-classic.item.active.bg.color: {labwc_color(colors['selection'])}",
        f"osd.window-switcher.style-classic.item.icon.size: {sw['iconSize']}",
        "",
    ]
    return "\n".join(lines)


# --- Button SVGs --------------------------------------------------------------

def glyph_svg(kind, x0, y0, s, color):
    """The caption glyph inside the s*s box at (x0, y0); geometry follows
    LunaGlyph (common/src/LunaGlyph.cpp)."""
    lw = max(1, round(s / 7))

    def at(fx, fy):
        return x0 + fx * s, y0 + fy * s

    if kind == "iconify":
        x1, y1 = at(0.12, 0.72)
        x2, _ = at(0.6, 0)
        return f'<rect x="{x1:.2f}" y="{y1:.2f}" width="{x2 - x1:.2f}" height="{lw * 1.4:.2f}" fill="{color}"/>'
    if kind == "max":
        x1, y1 = at(0.1, 0.1)
        x2, y2 = at(0.9, 0.9)
        x1, y1, x2, y2 = round(x1) + 0.5, round(y1) + 0.5, round(x2) - 0.5, round(y2) - 0.5
        return (f'<rect x="{x1}" y="{y1}" width="{x2 - x1}" height="{y2 - y1}" fill="none" stroke="{color}" stroke-width="1"/>'
                f'<rect x="{x1 - 0.5}" y="{y1 - 0.5}" width="{x2 - x1 + 1}" height="{lw * 1.4:.1f}" fill="{color}"/>')
    if kind == "max_toggled":
        out = []
        for fx, fy in ((0.3, 0.06), (0.06, 0.3)):
            x1, y1 = at(fx, fy)
            x2, y2 = at(fx + 0.62, fy + 0.62)
            x1, y1, x2, y2 = round(x1) + 0.5, round(y1) + 0.5, round(x2) - 0.5, round(y2) - 0.5
            out.append(f'<rect x="{x1}" y="{y1}" width="{x2 - x1}" height="{y2 - y1}" fill="{"none" if fx > 0.2 else "url(#face)"}" stroke="{color}" stroke-width="1"/>'
                       f'<rect x="{x1 - 0.5}" y="{y1 - 0.5}" width="{x2 - x1 + 1}" height="{lw * 1.2:.1f}" fill="{color}"/>')
        return "".join(out)
    if kind == "close":
        (ax, ay), (bx, by) = at(0.18, 0.18), at(0.82, 0.82)
        return (f'<path d="M{ax:.2f} {ay:.2f} L{bx:.2f} {by:.2f} M{bx:.2f} {ay:.2f} L{ax:.2f} {by:.2f}" '
                f'stroke="{color}" stroke-width="{lw * 1.2:.2f}" stroke-linecap="square" fill="none"/>')
    raise ValueError(kind)


def button_svg(t, kind, active, hover, standalone=True, ident="b"):
    w, m = t["window"], metrics(t)
    b = w["buttons"]
    size, cell_h = m["button_w"], m["button_h"]
    yoff = (cell_h - size) / 2
    is_close = kind == "close"
    family = b["close"] if is_close else b["normal"]
    if active:
        stops = family["hover"] if hover else family["normal"]
    else:
        stops = family["hover"] if hover else b["inactive"]
    glyph = b["closeGlyphColor"] if is_close and (active or hover) else b["glyphColor"]
    gcolor, _ = svg_color(glyph)
    border, border_a = svg_color(b["borderColor"])
    grad = "".join(
        f'<stop offset="{s["pos"]}" stop-color="{svg_color(s["color"])[0]}"'
        + ("" if svg_color(s["color"])[1] == 1 else f' stop-opacity="{svg_color(s["color"])[1]}"') + "/>"
        for s in stops)
    inset = b["glyphInset"]
    body = (f'<defs><linearGradient id="face" x1="0" y1="0" x2="0" y2="1">{grad}</linearGradient></defs>'
            f'<rect x="0.5" y="{yoff + 0.5}" width="{size - 1}" height="{size - 1}" rx="{b["radius"]}" '
            f'fill="url(#face)" stroke="{border}"' + ("" if border_a == 1 else f' stroke-opacity="{border_a}"') + ' stroke-width="1"/>'
            + glyph_svg(kind, inset, yoff + inset, size - 2 * inset, gcolor))
    if not standalone:
        return body.replace('id="face"', f'id="{ident}"').replace("url(#face)", f"url(#{ident})")
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n'
            f'<!-- SPDX-License-Identifier: CC-BY-SA-4.0. Generated by tools/gen-labwc-theme.py; do not edit. -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{cell_h}" viewBox="0 0 {size} {cell_h}">'
            + body + "</svg>\n")


BUTTONS = ("iconify", "max", "max_toggled", "close")


def button_files(t):
    out = {}
    for kind in BUTTONS:
        for active in (True, False):
            for hover in (False, True):
                name = f"{kind}{'_hover' if hover else ''}-{'active' if active else 'inactive'}.svg"
                out[name] = button_svg(t, kind, active, hover)
    return out


def contact_sheet(t):
    m = metrics(t)
    col_w, row_h, label_w = m["button_w"] + 12, m["button_h"] + 8, 90
    parts, y = [], 4
    states = [(True, False, "active"), (True, True, "active hover"), (False, False, "inactive"), (False, True, "inactive hover")]
    for active, hover, label in states:
        parts.append(f'<text x="4" y="{y + m["button_h"] / 2 + 4}" font-family="sans-serif" font-size="10">{label}</text>')
        for i, kind in enumerate(BUTTONS):
            ident = f"g{len(parts)}"
            parts.append(f'<g transform="translate({label_w + i * col_w} {y})">'
                         + button_svg(t, kind, active, hover, standalone=False, ident=ident) + "</g>")
        y += row_h
    width = label_w + len(BUTTONS) * col_w
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{y + 4}">'
            f'<rect width="100%" height="100%" fill="#ffffff"/>' + "".join(parts) + "</svg>\n")


# --- rc.xml -------------------------------------------------------------------

def rc_xml(template, t):
    title = t["fonts"]["title"]
    ui = t["fonts"]["ui"]
    values = {
        "{{HEADER}}": HEADER.format(scheme=DEFAULT_SCHEME),
        "{{THEME_NAME}}": THEME_NAMES[DEFAULT_SCHEME],
        "{{CORNER_RADIUS}}": str(t["window"]["titlebar"]["radiusTop"]),
        "{{TITLE_FONT}}": ",".join(f for f in title["families"] if f != "sans-serif") + ",sans",
        "{{TITLE_SIZE}}": str(px_to_pt(title["pixelSize"])),
        "{{TITLE_WEIGHT}}": "bold" if title.get("bold") else "normal",
        "{{UI_FONT}}": ",".join(f for f in ui["families"] if f != "sans-serif") + ",sans",
        "{{UI_SIZE}}": str(px_to_pt(ui["pixelSize"])),
    }
    out = template
    for k, v in values.items():
        out = out.replace(k, v)
    leftovers = sorted(set(re.findall(r"\{\{[A-Z_]+\}\}", out)))
    if leftovers:
        raise SystemExit(f"rc.xml.in: unknown placeholders {leftovers}")
    return out


# --- Driver ---------------------------------------------------------------------

def generate(theme_dir, rc_template):
    """All generated files as {relative path: text}."""
    files = {}
    for scheme, name in THEME_NAMES.items():
        t = json.loads((theme_dir / scheme / "theme.json").read_text())
        base = f"decorations/labwc/{name}/labwc"
        files[f"{base}/themerc"] = themerc(scheme, t)
        for fname, text in button_files(t).items():
            files[f"{base}/{fname}"] = text
    blue = json.loads((theme_dir / DEFAULT_SCHEME / "theme.json").read_text())
    files["session/labwc/rc.xml"] = rc_xml(rc_template.read_text(), blue)
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT), help="source tree (default: this checkout)")
    ap.add_argument("--check", action="store_true", help="fail if committed files differ from the tokens")
    ap.add_argument("--contact-sheet", metavar="OUT.svg")
    ap.add_argument("--scheme", default=DEFAULT_SCHEME)
    ap.add_argument("--grab", metavar="OUT.png", help="with --contact-sheet: also render it to a PNG (rsvg-convert, 3x)")
    args = ap.parse_args()
    root = Path(args.root)

    if args.contact_sheet or args.grab:
        t = json.loads((root / "theme" / args.scheme / "theme.json").read_text())
        svg = Path(args.contact_sheet) if args.contact_sheet else Path(tempfile.mkdtemp()) / "sheet.svg"
        svg.write_text(contact_sheet(t))
        if args.grab:
            if not shutil.which("rsvg-convert"):
                print("SKIP: rsvg-convert not installed")
                return 77
            subprocess.run(["rsvg-convert", "-z", "3", str(svg), "-o", args.grab], check=True)
        return 0

    files = generate(root / "theme", root / "session/labwc/rc.xml.in")
    if args.check:
        stale = []
        for rel, text in files.items():
            path = root / rel
            current = path.read_text() if path.exists() else ""
            if current != text:
                stale.append(rel)
                sys.stdout.writelines(list(difflib.unified_diff(current.splitlines(True), text.splitlines(True), rel, rel + " (generated)"))[:40])
        # Generated directories must not hold leftovers from old schemes.
        known = {root / rel for rel in files}
        for path in (root / "decorations/labwc").glob("*/labwc/*"):
            if path.is_file() and path not in known:
                stale.append(f"{path.relative_to(root)} (not generated)")
        print(f"{len(files)} generated files: {'OK' if not stale else 'OUT OF DATE: ' + ', '.join(stale)}")
        if stale:
            print("run tools/gen-labwc-theme.py and commit the result")
        return 1 if stale else 0

    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
